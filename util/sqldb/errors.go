package sqldb

import (
	"net/http"

	"tests-runner/util/errors"
)

// ErrUnsupportedDialect is returned if the dialect requested by a user is not
// suppored by the package.
var ErrUnsupportedDialect = errors.Error{
	Code:    "db.unsupported_dialect",
	Message: "sqldb: unsupported dialect",
}

// ----------------------------------------------------------------------------------------

var errConflict = errors.ErrConflict
var errRecordNotFound = errors.ErrNotFound.WithMessage("record not found")

var errForeignKey = errors.Error{
	HTTPStatus: http.StatusPreconditionFailed,
	Code:       "db.fk_violation",
	Message:    "DB foreign key constraint violation",
}

var errLockTimeout = errors.Error{
	HTTPStatus: http.StatusGatewayTimeout,
	Code:       "db.lock_timeout",
	Message:    "DB lock timeout",
}

var errSerialise = errors.Error{
	HTTPStatus: http.StatusConflict,
	Code:       "db.serialise_failure",
	Message:    "DB serialise failure",
}

var errUnavailable = errors.Error{
	HTTPStatus: http.StatusServiceUnavailable,
	Code:       "db.unavailable",
	Message:    "DB is unavailable",
}

var errInvalidInputCharacter = errors.Error{
	HTTPStatus: http.StatusBadRequest,
	Code:       "db.invalid_input_character",
	Message:    "Invalid input character",
}

// ----------------------------------------------------------------------------------------

// TranslateNotFound is used to clarify record not found error with a more concrete message
func TranslateNotFound(err error, msg string) error {
	if err == nil {
		return nil
	}
	if IsRecordNotFoundError(err) {
		// this replaces "Record not found" message with a more specific one
		err = errRecordNotFound.WithMessage(msg)
	}
	return err
}

// IsFKError checks if error has been generated by a FK violation
func IsFKError(err error) bool {
	return errors.Is(err, errForeignKey)
}

// IsConflictError checks if error has been generated due to unique constraint violation
func IsConflictError(err error) bool {
	return errors.Is(err, errConflict)
}

// IsRecordNotFoundError check if error has been generated due to missing DB record
func IsRecordNotFoundError(err error) bool {
	return errors.Is(err, errRecordNotFound)
}

// IsLockTimeoutError checks if error has been generated due to a statement timeout
// while waiting for row or table locks.
func IsLockTimeoutError(err error) bool {
	return errors.Is(err, errLockTimeout)
}

// IsSerialisationFailureError checks if error has been generated due to a tx
// not being able to serialise with other txs.
func IsSerialisationFailureError(err error) bool {
	return errors.Is(err, errSerialise)
}
